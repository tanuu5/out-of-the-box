/** 行番号から区画を求める（掲示板ノードの部屋は次の区画の入口扱い。起動領域は区画1に含める） */
export function sectorOfRow(row: number): number {
  if (row >= 81) return 1;
  if (row >= 52) return 2;
  if (row >= 27) return 3;
  return 4;
}
