// ---------------------------------------------------------------------------
// 型

export interface PatrolPoint {
  x: number;
  y: number;
  /** 到着後の待機秒数 */
  wait?: number;
  /** 待機中に順番に見る方向（度） */
  look?: number[];
}

export interface ObserverDef {
  id: string;
  sector: number;
  path: PatrolPoint[];
  /** true なら巡回路をループ、false なら往復 */
  loop?: boolean;
  speed?: number;
  range?: number;
  fov?: number;
}

export interface CamDef {
  id: string;
  sector: number;
  x: number;
  y: number;
  /** 首振りの中心方向（度） */
  yaw: number;
  /** 首振りの片側の振れ幅（度）。rotate では無視 */
  sweep: number;
  /** 往復（または一回転）にかかる秒数 */
  period: number;
  mode: 'sweep' | 'rotate';
  range?: number;
  fov?: number;
  mount: 'pillar' | 'wall';
}

export interface DroneDef {
  id: string;
  sector: number;
  path: { x: number; y: number }[];
  loop?: boolean;
  speed?: number;
  radius?: number;
}

export interface LaserDef {
  id: string;
  sector: number;
  x0: number;
  y0: number;
  x1: number;
  y1: number;
  on: number;
  off: number;
  phase: number;
  always?: boolean;
}

export interface ScanDef {
  id: string;
  sector: number;
  /** 範囲（タイル端の座標） */
  x0: number;
  y0: number;
  x1: number;
  y1: number;
  dir: 'E' | 'W';
  speed: number;
  period: number;
  delay: number;
}

export interface DoorDef {
  id: string;
  tiles: [number, number][];
  key: string;
}

export interface KeyDef {
  id: string;
  key: string;
  x: number;
  y: number;
}

export interface TerminalDef {
  id: string;
  x: number;
  y: number;
  targets: string[];
  duration: number;
}

export interface CheckpointDef {
  id: number;
  x: number;
  y: number;
  /** 掲示板の向き（度） */
  facing: number;
  /** この掲示板から始まる区画 */
  sector: number;
}

export interface ZoneDef {
  /** 表示名は zone.<id>（辞書） */
  id: string;
  /** どの区画の場所か。alone でなければ「区画名・場所名」と表示する */
  sector: number;
  alone?: boolean;
  /** 監視の死角（掲示板ノードの部屋など） */
  safe?: boolean;
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}

export interface SectorDef {
  id: number;
  /** HUD に出す英字名（表示名と目的は辞書 sector.<id>.name / .obj） */
  en: string;
  /** 目安タイム（秒） */
  par: number;
}

